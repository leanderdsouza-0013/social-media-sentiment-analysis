CREATE DATABASE IF NOT EXISTS social_media_sentiment;
USE social_media_sentiment;

SELECT COUNT(*) AS total_rows from twitter_sentiment;

SELECT * from twitter_sentiment LIMIT 10;

SELECT SENTIMENT, COUNT(*) AS TWEET_COUNT FROM TWITTER_SENTIMENT GROUP BY SENTIMENT ORDER BY TWEET_COUNT DESC;

SELECT SENTIMENT, COUNT(*) AS TWEET_COUNT, ROUND(COUNT(*)*100.0/(SELECT COUNT(*) FROM TWITTER_SENTIMENT), 2) AS PERCENTAGE
FROM TWITTER_SENTIMENT GROUP BY SENTIMENT ORDER BY PERCENTAGE DESC;

SELECT ENTITY, SENTIMENT, COUNT(*) AS TWEET_COUNT
FROM TWITTER_SENTIMENT GROUP BY ENTITY, SENTIMENT
ORDER BY ENTITY, TWEET_COUNT DESC;

SELECT ENTITY, COUNT(*) AS TWEET_COUNT
FROM TWITTER_SENTIMENT
GROUP BY ENTITY
ORDER BY TWEET_COUNT DESC
LIMIT 10;

SELECT ENTITY, COUNT(*) AS POSITIVE_TWEETS FROM TWITTER_SENTIMENT WHERE SENTIMENT = 'POSITIVE' 
GROUP BY ENTITY ORDER BY POSITIVE_TWEETS DESC
LIMIT 10;

SELECT ENTITY, COUNT(*) AS NEGATIVE_TWEETS FROM TWITTER_SENTIMENT WHERE SENTIMENT = 'NEGATIVE' 
GROUP BY ENTITY ORDER BY NEGATIVE_TWEETS DESC
LIMIT 10;

SELECT ENTITY, COUNT(*) AS TOTAL_TWEETS,
SUM(SENTIMENT='POSITIVE') AS POSITIVE_TWEETS,
SUM(SENTIMENT='NEGATIVE') AS NEGATIVE_TWEETS,
SUM(SENTIMENT='NEUTRAL') AS NEUTRAL_TWEETS,
SUM(SENTIMENT='IRRELEVANT') AS IRRELEVANT_TWEETS,
ROUND(SUM(SENTIMENT='POSITIVE')*100.0/COUNT(*),2) AS POSITIVE_PERCENTAGE
FROM TWITTER_SENTIMENT GROUP BY ENTITY ORDER BY POSITIVE_PERCENTAGE DESC;

SELECT ENTITY, SENTIMENT, TWEET_LENGTH, TEXT FROM TWITTER_SENTIMENT ORDER BY TWEET_LENGTH DESC LIMIT 10;

SELECT SENTIMENT, COUNT(*) AS TWEET_COUNT, ROUND(AVG(TWEET_LENGTH),2) AS AVERAGE_LENGTH,
MIN(TWEET_LENGTH) AS SHORTEST_TWEET_LENGTH,
MAX(TWEET_LENGTH) AS LONGEST_TWEET_LENGTH
FROM TWITTER_SENTIMENT GROUP BY SENTIMENT ORDER BY AVERAGE_LENGTH DESC;
